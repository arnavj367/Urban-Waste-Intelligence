"""Always-on RTSP worker. Run separately from Streamlit under a process supervisor."""
import json, logging, os, time
from pathlib import Path
import cv2
import requests
from dotenv import load_dotenv

ROOT = Path(__file__).resolve().parent
load_dotenv(ROOT / ".env")
from src.database import init_db, create_report, find_recent_duplicate, get_report
from src.dispatch import assign_vehicle
from src.notifications import send_incident_webhook, build_incident_event
from src.vision import analyze_image

logging.basicConfig(level=os.getenv("LOG_LEVEL","INFO"), format="%(asctime)s %(levelname)s %(message)s")
log = logging.getLogger("uwi-camera")
STATUS_PATH = ROOT / "data" / "camera_status.json"


def write_status(**updates):
    STATUS_PATH.parent.mkdir(parents=True, exist_ok=True)
    current = {}
    if STATUS_PATH.exists():
        try: current = json.loads(STATUS_PATH.read_text(encoding="utf-8"))
        except Exception: pass
    current.update(updates)
    current["last_heartbeat"] = time.time()
    STATUS_PATH.write_text(json.dumps(current, indent=2), encoding="utf-8")


def main():
    source = os.getenv("UWI_CAMERA_URL", "").strip()
    if not source: raise SystemExit("Set UWI_CAMERA_URL in .env or the worker environment.")
    init_db()
    lat = float(os.getenv("UWI_CAMERA_LAT","26.8467")); lon = float(os.getenv("UWI_CAMERA_LON","80.9462"))
    location = os.getenv("UWI_CAMERA_LOCATION","Camera monitored area")
    interval = max(5,int(os.getenv("UWI_FRAME_INTERVAL_SECONDS","20")))
    cooldown = max(60,int(os.getenv("UWI_ALERT_COOLDOWN_SECONDS","900")))
    min_conf = max(0,min(100,int(os.getenv("UWI_MIN_CONFIDENCE","70"))))
    last_alert, last_frame, last_heartbeat = 0.0, 0.0, 0.0
    cap = None
    log.info("Starting authorized camera worker · interval=%ss · location=%s", interval, location)
    try:
        while True:
            if cap is None or not cap.isOpened():
                if cap is not None: cap.release()
                cap = cv2.VideoCapture(source, cv2.CAP_FFMPEG)
                cap.set(cv2.CAP_PROP_BUFFERSIZE, 1)
                if not cap.isOpened():
                    write_status(state="reconnecting", last_error="Unable to open camera stream")
                    log.warning("Camera unavailable; retrying in 10 seconds")
                    time.sleep(10); continue
                write_status(state="connected", last_error="")
                log.info("Camera connected")
            ok, frame = cap.read()
            if not ok:
                write_status(state="reconnecting", last_error="Frame read failed")
                cap.release(); cap = None; time.sleep(5); continue
            now = time.time()
            if now - last_frame >= interval:
                last_frame = now
                ok, jpg = cv2.imencode(".jpg", frame, [int(cv2.IMWRITE_JPEG_QUALITY), 86])
                if ok:
                    vision = analyze_image(jpg.tobytes(), ROOT)
                    severity = vision.get("severity","Needs Review")
                    write_status(state="connected", last_severity=severity, last_confidence=vision.get("confidence",0), last_assessment=now, last_error="")
                    log.info("Frame assessment: severity=%s confidence=%s", severity, vision.get("confidence",0))
                    if severity in ("High","Critical") and vision.get("waste_present") and int(vision.get("confidence",0)) >= min_conf and now-last_alert >= cooldown:
                        duplicate = find_recent_duplicate(lat,lon,100,30)
                        if duplicate:
                            log.info("Nearby open incident %s already exists; suppressing duplicate", duplicate["id"])
                        else:
                            rid = create_report(jpg.tobytes(),ROOT,location,lat,lon,"Automated camera","Generated by continuous authorized camera monitoring",severity,vision)
                            assignment = assign_vehicle(rid)
                            event = build_incident_event(get_report(rid),assignment)
                            delivery = send_incident_webhook(event)
                            write_status(last_incident_id=rid,last_alert=now,last_webhook_status=delivery.get("status"))
                            log.warning("PRIORITY INCIDENT %s | %s | assignment=%s | webhook=%s",rid,severity,assignment.get("reason"),delivery.get("status"))
                            last_alert = now
            elif now - last_heartbeat >= 15:
                write_status(state="connected")
                last_heartbeat = now
            time.sleep(0.15)
    finally:
        if cap is not None: cap.release()
        write_status(state="stopped")

if __name__ == "__main__": main()
